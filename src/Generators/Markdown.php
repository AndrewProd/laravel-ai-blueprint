<?php

declare(strict_types=1);

namespace AndrewProd\AiBlueprint\Generators;

use AndrewProd\AiBlueprint\Support\Version;

final class Markdown
{
    public static function header(string $generator): string
    {
        return '<!-- Generated by Laravel AI Blueprint ('.$generator.', template v'.Version::TEMPLATES.'). '
            .'Manual edits are detected by `php artisan ai-blueprint:sync` and are never overwritten without --force. -->';
    }

    /**
     * @param  list<string>  $headers
     * @param  list<list<string>>  $rows
     */
    public static function table(array $headers, array $rows): string
    {
        $lines = [
            '| '.implode(' | ', array_map([self::class, 'cell'], $headers)).' |',
            '|'.str_repeat(' --- |', count($headers)),
        ];
        foreach ($rows as $row) {
            $lines[] = '| '.implode(' | ', array_map([self::class, 'cell'], $row)).' |';
        }

        return implode("\n", $lines);
    }

    /**
     * @param  list<string>  $items
     */
    public static function bullets(array $items, string $empty = '_None._'): string
    {
        if ($items === []) {
            return $empty;
        }

        return implode("\n", array_map(static fn (string $item): string => '- '.$item, $items));
    }

    /**
     * @param  list<string>  $items
     */
    public static function checklist(array $items): string
    {
        return implode("\n", array_map(static fn (string $item): string => '- [ ] '.$item, $items));
    }

    public static function code(string $value): string
    {
        return '`'.str_replace('`', "'", $value).'`';
    }

    /**
     * Text taken from the project (names, paths) is data: neutralize characters that
     * could break the surrounding markdown structure.
     */
    public static function cell(string $value): string
    {
        return str_replace(['|', "\n", "\r"], ['\|', ' ', ''], $value);
    }

    /**
     * @param  list<string>  $blocks
     */
    public static function document(array $blocks): string
    {
        $blocks = array_values(array_filter($blocks, static fn (string $b): bool => trim($b) !== ''));

        return rtrim(implode("\n\n", $blocks))."\n";
    }
}
