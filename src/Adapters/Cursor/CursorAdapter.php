<?php

declare(strict_types=1);

namespace AndrewProd\AiBlueprint\Adapters\Cursor;

use AndrewProd\AiBlueprint\Contracts\AgentAdapter;
use AndrewProd\AiBlueprint\Generators\AgentContext;
use AndrewProd\AiBlueprint\Generators\AgentInstructions\AgentInstructions;
use AndrewProd\AiBlueprint\Generators\GeneratedArtifact;
use AndrewProd\AiBlueprint\Generators\Markdown;
use AndrewProd\AiBlueprint\Support\Version;

/**
 * Cursor project rules: .mdc files in .cursor/rules/ with YAML front matter
 * (description, globs, alwaysApply).
 */
final class CursorAdapter implements AgentAdapter
{
    public function name(): string
    {
        return 'cursor';
    }

    public function supportedFiles(): array
    {
        return ['.cursor/rules/ai-blueprint.mdc', '.cursor/rules/ai-blueprint-testing.mdc'];
    }

    public function render(AgentContext $context): iterable
    {
        $instructions = new AgentInstructions($context);

        yield new GeneratedArtifact('.cursor/rules/ai-blueprint.mdc', $this->rule(
            'Project architecture, rules and verification steps generated by Laravel AI Blueprint',
            null,
            true,
            'cursor.rules.project',
            ['# Project rules', ...$instructions->all()],
        ), 'cursor.rules.project', 'instructions', Version::TEMPLATES);

        yield new GeneratedArtifact('.cursor/rules/ai-blueprint-testing.mdc', $this->rule(
            'Testing rules for this project',
            'tests/**',
            false,
            'cursor.rules.testing',
            [
                '# Testing rules',
                $instructions->verification(),
                Markdown::bullets([
                    'Never claim tests passed unless they were run.',
                    'Tests must not call real external services or production databases.',
                    'Do not put secrets or real customer data in fixtures.',
                ]),
            ],
        ), 'cursor.rules.testing', 'instructions', Version::TEMPLATES);
    }

    /**
     * @param  list<string>  $blocks
     */
    private function rule(string $description, ?string $globs, bool $alwaysApply, string $generator, array $blocks): string
    {
        // Front matter must be the first thing in the file; the managed-file comment follows it.
        $frontMatter = "---\ndescription: {$description}\nglobs: ".($globs ?? '')."\nalwaysApply: ".($alwaysApply ? 'true' : 'false')."\n---";

        return $frontMatter."\n".Markdown::document([Markdown::header($generator), ...$blocks]);
    }
}
